#!/usr/bin/env python3
"""Validate a maze grid and add it as a custom level.

Usage:
  python3 add_level.py my_maze.txt --name "Rainbow Maze"   # validate + add
  python3 add_level.py my_maze.txt --check                  # validate only
  python3 add_level.py --rebuild                            # regenerate levels/custom.js
Grid chars: # wall, . path (space also ok), S start, E black hole, * star.
"""
import sys, os, re, json, argparse
from collections import deque
HERE=os.path.dirname(os.path.abspath(__file__)); CDIR=os.path.join(HERE,'levels','custom')

def parse(text):
    lines=[l.rstrip('\n').rstrip() for l in text.splitlines()]
    lines=[l for l in lines if l.strip() and not l.lstrip().startswith(';')]
    if not lines: raise ValueError('empty grid')
    w=max(len(l) for l in lines)
    g=[(l.replace(' ','.')+'#'*(w-len(l))) for l in lines]
    # surround with walls if edges are open
    if any(c!='#' for c in g[0]+g[-1]) or any(r[0]!='#' or r[-1]!='#' for r in g):
        g=['#'*(w+2)]+['#'+r+'#' for r in g]+['#'*(w+2)]
    return g

def validate(g):
    errs=[]; bad=set(''.join(g))-set('#.SE*')
    if bad: errs.append(f'unknown characters: {"".join(sorted(bad))} (use # . S E *)')
    S=[(r,c) for r,row in enumerate(g) for c,ch in enumerate(row) if ch=='S']
    E=[(r,c) for r,row in enumerate(g) for c,ch in enumerate(row) if ch=='E']
    if len(S)!=1: errs.append(f'need exactly one S (start), found {len(S)}')
    if len(E)!=1: errs.append(f'need exactly one E (black hole), found {len(E)}')
    if len(g)>40 or len(g[0])>40: errs.append('grid too big (max 40x40)')
    if errs: return errs,None
    seen={S[0]}; q=deque([S[0]])
    while q:
        r,c=q.popleft()
        for dr,dc in((1,0),(-1,0),(0,1),(0,-1)):
            n=(r+dr,c+dc)
            if 0<=n[0]<len(g) and 0<=n[1]<len(g[0]) and g[n[0]][n[1]]!='#' and n not in seen: seen.add(n); q.append(n)
    if E[0] not in seen: errs.append('the black hole (E) cannot be reached from S')
    stars=[(r,c) for r,row in enumerate(g) for c,ch in enumerate(row) if ch=='*']
    unreach=[s for s in stars if s not in seen]
    if unreach: errs.append(f'{len(unreach)} star(s) cannot be reached')
    return errs,len(stars)

def rebuild():
    levels=[]
    for f in sorted(os.listdir(CDIR)):
        if not f.endswith('.txt'): continue
        txt=open(os.path.join(CDIR,f)).read(); m=re.search(r'^;\s*name:\s*(.+)$',txt,re.M)
        name=m.group(1).strip() if m else f[:-4].replace('_',' ').title()
        g=parse(txt); errs,_=validate(g)
        if errs: print(f'SKIP {f}: '+'; '.join(errs)); continue
        levels.append({'name':name,'grid':g})
    with open(os.path.join(HERE,'levels','custom.js'),'w') as o:
        o.write('// AUTO-GENERATED by add_level.py from levels/custom/*.txt - do not edit by hand\n')
        o.write('window.CUSTOM_LEVELS = '+json.dumps(levels,indent=1)+';\n')
    print(f'levels/custom.js: {len(levels)} custom level(s)')

if __name__=='__main__':
    ap=argparse.ArgumentParser(); ap.add_argument('file',nargs='?'); ap.add_argument('--name'); ap.add_argument('--check',action='store_true'); ap.add_argument('--rebuild',action='store_true')
    a=ap.parse_args()
    if a.rebuild or not a.file: rebuild(); sys.exit(0)
    g=parse(open(a.file).read()); errs,ns=validate(g)
    print('\n'.join(g))
    if errs: print('INVALID:\n - '+'\n - '.join(errs)); sys.exit(1)
    print(f'OK: {len(g[0])}x{len(g)} grid, {ns} stars, black hole reachable')
    if a.check: sys.exit(0)
    name=a.name or os.path.splitext(os.path.basename(a.file))[0].replace('_',' ').title()
    slug=re.sub(r'[^a-z0-9]+','_',name.lower()).strip('_') or 'maze'
    os.makedirs(CDIR,exist_ok=True); out=os.path.join(CDIR,slug+'.txt'); k=2
    while os.path.exists(out): out=os.path.join(CDIR,f'{slug}_{k}.txt'); k+=1
    open(out,'w').write(f'; name: {name}\n'+'\n'.join(g)+'\n'); print('saved',out); rebuild()
