import random, json
from add_level import validate
from collections import deque
def maze(cw,ch,seed,loops):
    R=random.Random(seed); W,H=cw*2+1,ch*2+1; g=[['#']*W for _ in range(H)]
    st=[(0,0)]; seen={(0,0)}; g[1][1]='.'
    while st:
        x,y=st[-1]; nb=[(x+dx,y+dy) for dx,dy in((1,0),(-1,0),(0,1),(0,-1)) if 0<=x+dx<cw and 0<=y+dy<ch and (x+dx,y+dy) not in seen]
        if not nb: st.pop(); continue
        nx,ny=R.choice(nb); g[y+ny+1][x+nx+1]='.'; g[ny*2+1][nx*2+1]='.'; seen.add((nx,ny)); st.append((nx,ny))
    for _ in range(loops):
        while True:
            r,c=R.randrange(1,H-1),R.randrange(1,W-1)
            if g[r][c]=='#' and ((g[r-1][c]=='.'==g[r+1][c] and g[r][c-1]=='#'==g[r][c+1]) or (g[r][c-1]=='.'==g[r][c+1] and g[r-1][c]=='#'==g[r+1][c])): g[r][c]='.'; break
    g[1][1]='S'; g[H-2][W-2]='E'
    # path for stars
    prev={(1,1):None}; q=deque([(1,1)])
    while q:
        p=q.popleft()
        for d in((1,0),(-1,0),(0,1),(0,-1)):
            n=(p[0]+d[0],p[1]+d[1])
            if g[n[0]][n[1]]!='#' and n not in prev: prev[n]=p; q.append(n)
    path=[]; p=(H-2,W-2)
    while p: path.append(p); p=prev[p]
    path=path[::-1][2:-2]
    for p in path[::3]: g[p[0]][p[1]]='*'
    opens=[(r,c) for r in range(H) for c in range(W) if g[r][c]=='.' and (r,c) not in path]
    for p in R.sample(opens,min(len(opens),cw//2)): g[p[0]][p[1]]='*'
    return [''.join(r) for r in g]
specs=[("Starry Start",4,3,1,3),("Moon Path",5,4,2,2),("Comet Corner",6,5,3,3),("Planet Puzzle",7,5,4,4),("Galaxy Garden",8,6,5,5)]
L=[]
for name,cw,ch,seed,loops in specs:
    g=maze(cw,ch,seed*7+1,loops); e,_=validate(g); assert not e,e; L.append({'name':name,'grid':g}); print(name); print('\n'.join(g))
open('levels/builtin.js','w').write('// Built-in levels (generated by gen_builtin.py)\nwindow.BUILTIN_LEVELS = '+json.dumps(L,indent=1)+';\n')
